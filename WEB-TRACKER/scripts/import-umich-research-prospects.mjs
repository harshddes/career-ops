function decodeCloudflareEmail(hex) {
  const key = Number.parseInt(hex.slice(0, 2), 16);
  let email = '';
  for (let i = 2; i < hex.length; i += 2) {
    email += String.fromCharCode(Number.parseInt(hex.slice(i, i + 2), 16) ^ key);
  }
  return email;
}

function normalizedName(value) {
  return String(value || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}

function plainText(html) {
  return String(html || '')
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ');
}

async function fetchText(url, cache) {
  if (!url || !/^https?:\/\//i.test(url)) return '';
  if (cache.has(url)) return cache.get(url);
  try {
    const res = await fetch(url, { redirect: 'follow' });
    if (!res.ok) {
      cache.set(url, '');
      return '';
    }
    const text = await res.text();
    cache.set(url, text);
    return text;
  } catch {
    cache.set(url, '');
    return '';
  }
}

function extractEmailNearName(html, name) {
  if (!html || !name) return '';
  const decodedHtml = html.replace(/data-cfemail="([a-f0-9]+)"/gi, (_, hex) => decodeCloudflareEmail(hex));
  const text = plainText(decodedHtml);
  const nameIndex = text.toLowerCase().indexOf(String(name).toLowerCase());
  if (nameIndex < 0) return '';
  const windows = [text.slice(Math.max(0, nameIndex - 1200), nameIndex + 2000)];

  for (const windowText of windows) {
    const match = windowText.match(/[A-Z0-9._%+-]+@umich\.edu/i);
    if (match) return match[0];
  }
  return '';
}

async function enrichProspect(prospect, cache) {
  if (prospect.skip_email_enrichment) return prospect;
  if (prospect.contact_email) return prospect;
  const urls = [
    prospect.profile_url,
    prospect.lab_url,
    prospect.contact_page,
    MIPSE_MEMBERS_URL,
    CUOS_PEOPLE_URL,
    PEPL_PERSONNEL_URL,
  ].filter(Boolean);

  for (const url of [...new Set(urls)]) {
    const html = await fetchText(url, cache);
    const email = extractEmailNearName(html, prospect.name);
    if (email) return { ...prospect, contact_email: email };
  }
  return prospect;
}

function validateProspects(items) {
  const seen = new Set();
  const errors = [];
  for (const prospect of items) {
    if (!prospect.name) errors.push(`${prospect.id || 'unknown'} missing name`);
    if (!prospect.department) errors.push(`${prospect.name || prospect.id} missing department`);
    if (!Number.isFinite(Number(prospect.score))) errors.push(`${prospect.name || prospect.id} missing score`);
    if (!prospect.profile_url && !prospect.lab_url && !prospect.evidence?.some(item => item.url)) {
      errors.push(`${prospect.name || prospect.id} missing source URL`);
    }
    const key = `${normalizedName(prospect.name)}|${normalizedName(prospect.department)}|${prospect.contact_email || prospect.profile_url}`;
    if (seen.has(key)) errors.push(`${prospect.name || prospect.id} appears duplicated`);
    seen.add(key);
  }
  return errors;
}

